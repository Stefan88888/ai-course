# variables_practice.py
# Practicing different data types

# String (текст)
my_name = "Stepan"

# Integer (целое число)
my_age = 24

# Float (дробное число)
my_height = 185.5

# Boolean (Истина / Ложь)
is_student = True

# Print them all
print("Name:", my_name)
print("Age:", my_age)
print("Height:", my_height)
print("Is student?", is_student)

# Меняем значение переменной
my_age = 25  # У меня день рождения
print("Updated age:", my_age)